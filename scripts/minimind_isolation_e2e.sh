#!/usr/bin/env bash
# Provision a real MiniMind key-isolation boundary (Linux) and run the OS-level adversarial tests
# under distinct UIDs. Must run as root on a disposable host/runner. Exit != 0 on any failure.
#
#   sudo bash scripts/minimind_isolation_e2e.sh <repo_dir> <python_with_pytest>
#
# Identities: aios-parent (AIOS parent), aios-minimind (workload, owns key), aios-agent (other agent).
set -euo pipefail
SRC=$(realpath "$1"); PY=$2
[ "$(id -u)" = 0 ] || { echo "must run as root" >&2; exit 2; }
case "$(uname -s)" in Linux) ;; *) echo "BLOCKED: unsupported platform $(uname -s)" >&2; exit 2;; esac

PARENT=aios-parent; WL=aios-minimind; AGENT=aios-agent
BASE=/usr/lib/aios-minimind; KEYDIR=/var/lib/aios-minimind/keys; KEY=$KEYDIR/ed25519.pem
LAUNCHER=$BASE/bin/minimind-workload; FIXTURE=$BASE/etc/test-fixture.json
NEG=/opt/aios-minimind-neg; WORK=/srv/aios-test; LOGS=/tmp/aios-isolation-logs

for u in $PARENT $WL $AGENT; do id "$u" >/dev/null 2>&1 || useradd --system --user-group --no-create-home --shell /usr/sbin/nologin "$u"; done
/usr/bin/python3 -c 'import cryptography' 2>/dev/null || { apt-get update -qq && apt-get install -y -qq python3-cryptography; }

# Root-owned workload code, config and launcher (parent cannot modify what runs as the workload).
rm -rf "$BASE" "$NEG"
install -d -o root -g root -m 0755 "$BASE" "$BASE/lib" "$BASE/bin" "$BASE/etc" "$NEG"
cp -r "$SRC/adapters" "$SRC/core" "$BASE/lib/"
find "$BASE/lib" -name __pycache__ -prune -exec rm -rf {} +
[ -d "$SRC/contracts" ] && cp -r "$SRC/contracts" "$BASE/lib/"
chown -R root:root "$BASE/lib"; chmod -R go-w,a+rX "$BASE/lib"
cat > "$BASE/bin/receipt-demo.py" <<'PYEOF'
import json, sys, time
req = json.load(sys.stdin); time.sleep(1.5)
a = {k: "sha256:" + k for k in ("workload_revision", "dataset_digest", "tokenizer_digest", "model_digest", "environment_digest")}
print(json.dumps({"minimind_receipt": {"capability": "minimind.learning@1", "task_id": req["contract"]["task_id"],
      "terminal_state": "PROMOTE", "artifacts": a,
      "evidence": {"training_receipt": {**a, "steps": 1}, "provenance": {**a},
                   "evaluation_receipt": {**a, "independent": True, "holdout": True}}}}))
PYEOF
cat > "$BASE/etc/workload.json" <<EOF
{"provider": "minimind", "key_path": "$KEY", "receipt_command": ["/usr/bin/python3", "-I", "$BASE/bin/receipt-demo.py"], "timeout": 60, "ttl": 300}
EOF
printf '#!/bin/sh\nexec /usr/bin/python3 -I -B %s/lib/adapters/minimind/workload_entry.py %s/etc/workload.json\n' "$BASE" "$BASE" > "$LAUNCHER"
chmod 0755 "$LAUNCHER"; chmod 0644 "$BASE/etc/workload.json" "$BASE/bin/receipt-demo.py"

# Workload-private key: generated by the workload identity, never touched by the parent.
rm -rf /var/lib/aios-minimind
install -d -o "$WL" -g "$WL" -m 0700 /var/lib/aios-minimind "$KEYDIR"
PUB=$(cd / && sudo -u "$WL" /usr/bin/python3 -I -c '
import os, sys
from cryptography.hazmat.primitives import serialization as s
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
k = Ed25519PrivateKey.generate(); os.umask(0o077)
fd = os.open(sys.argv[1], os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
os.write(fd, k.private_bytes(s.Encoding.PEM, s.PrivateFormat.PKCS8, s.NoEncryption())); os.close(fd)
print(k.public_key().public_bytes(s.Encoding.Raw, s.PublicFormat.Raw).hex())' "$KEY")
KID=$(PYTHONPATH="$SRC" python3 -I -c 'import sys; sys.path.insert(0, sys.argv[2]); from core.provider_ed25519 import key_id_for; print(key_id_for(sys.argv[1]))' "$PUB" "$SRC")

# Restricted sudo: parent may start exactly the launcher, with no arguments, as the workload only.
SUDOERS=/etc/sudoers.d/aios-minimind
printf '%s ALL=(%s) NOPASSWD: %s ""\n' "$PARENT" "$WL" "$LAUNCHER" > "$SUDOERS.tmp"
chmod 0440 "$SUDOERS.tmp"; visudo -cf "$SUDOERS.tmp" >/dev/null; mv "$SUDOERS.tmp" "$SUDOERS"

# Negative fixtures: a parent-readable key and a parent-owned launcher must both block.
install -d -m 0755 "$NEG/readable"; echo dummy > "$NEG/readable/ed25519.pem"; chmod 0644 "$NEG/readable/ed25519.pem"
install -o "$PARENT" -g "$PARENT" -m 0755 "$LAUNCHER" "$NEG/minimind-workload"

cat > "$FIXTURE" <<EOF
{"workload_user": "$WL", "launcher": "$LAUNCHER", "key_path": "$KEY", "public_key": "$PUB", "key_id": "$KID",
 "trusted_paths": ["$BASE/lib", "$BASE/etc/workload.json", "$BASE/bin/receipt-demo.py"],
 "trusted_files": ["$BASE/etc/workload.json", "$BASE/bin/receipt-demo.py", "$BASE/lib/adapters/minimind/workload_entry.py"],
 "neg_readable_key": "$NEG/readable/ed25519.pem", "neg_launcher": "$NEG/minimind-workload"}
EOF
chmod 0644 "$FIXTURE"

# Test checkout readable by the unprivileged identities (not trusted by the boundary).
rm -rf "$WORK" "$LOGS"; mkdir -p "$WORK" "$LOGS"
cp -r "$SRC/." "$WORK/"; rm -rf "$WORK/.git"; chown -R "$PARENT:$PARENT" "$WORK"; chmod -R a+rX "$WORK"; chmod 0777 "$LOGS"

# Non-secret diagnostics of the boundary actually provisioned.
ls -l /usr/bin/sudo; readlink -f /usr/bin/sudo; /usr/bin/sudo -V 2>&1 | head -1
(cd / && sudo -u "$PARENT" /usr/bin/sudo -n -l) || echo "parent sudo -l failed"

run_role() {  # role user
  (cd "$WORK" && sudo -u "$2" env -i PATH=/usr/bin:/bin HOME=/tmp PYTHONDONTWRITEBYTECODE=1 \
     AIOS_MINIMIND_ISOLATION_ROLE="$1" AIOS_MINIMIND_ISOLATION_FIXTURE="$FIXTURE" \
     "$PY" -m pytest -p no:cacheprovider -q -rA tests/test_minimind_key_isolation.py \
     --junitxml="$LOGS/$1.xml" 2>&1 | tee "$LOGS/$1.log")
}
status=0
run_role parent "$PARENT" || status=1
run_role agent "$AGENT" || status=1

# Root post-check: no private key material in any captured output.
BODY=$(sed -n '2p' "$KEY")
if grep -rqF "$BODY" "$LOGS"; then echo "FAIL: private key material found in test output" >&2; status=1; fi
for role in parent agent; do
  python3 - "$LOGS/$role.xml" "$role" <<'PYEOF' || status=1
import sys, xml.etree.ElementTree as ET
s = ET.parse(sys.argv[1]).getroot(); s = s if s.tag == "testsuite" else s[0]
t, f, e, k = (int(s.get(x, 0)) for x in ("tests", "failures", "errors", "skipped"))
print(f"{sys.argv[2]}: tests={t} failures={f} errors={e} skipped={k}")
expected = {"parent": 22, "agent": 17}[sys.argv[2]]
ran = t - k
if f or e or ran < expected: sys.exit(f"{sys.argv[2]}: expected >= {expected} executed OS tests, got {ran}")
PYEOF
done
exit $status
